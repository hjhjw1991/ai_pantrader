-- 止盈价 + 离场的 T+1 修正
--
-- 1. 止盈价（prediction.take_profit_px）
--
--    此前台账只有止损，没有止盈：推荐一旦成交，就一路拿到 horizon 期满。
--    实测（2026-10-23，影子盘 12,665 条可重放样本，按基准日 7:3 时间切分）这一条
--    的代价很具体 —— 样本外每信号净期望（扣 0.15% 双边成本）：
--
--      纯期满（无止盈）   +0.097%
--      止盈 4%            +0.209%
--      止盈 5%            +0.195%
--      止盈 8%            +0.182%
--
--    4~8% 是一片平台，样本内外方向一致，不是挑出来的尖峰。止损那条轴实测无效
--    （0.223~0.290 vs 不设止损的 0.292），移动止损单独用还是负的，都没采纳。
--
--    老行的 take_profit_px 一律留 NULL = 当时确实没设止盈，按期满结算，
--    不回填 —— 回填等于把后来才定的纪律记到老样本头上。
--
-- 2. T+1：离场最早只能从成交次日起
--
--    A 股当日买入不能当日卖出。此前止损扫描从 holdFrom 起算，而盘中成交的
--    holdFrom 就是成交当日 —— 等于允许当日买入当日止损离场，这条路径现实里不存在。
--    漏掉它的后果随止盈档位变小而放大：不设 T+1 时止盈 2% 看起来最优
--    （样本外 +1.37%），其中相当一部分是"当日冲高就卖"卖出来的；
--    加上 T+1 之后 2% 掉到 +0.245%，那个单调性整个消失。
--
--    MFE/MAE 不受影响：它量的是持仓期间出现过什么价，当日买入后隔夜的波动
--    确实是这笔仓位经历过的，不是可执行路径。
ALTER TABLE prediction ADD COLUMN take_profit_px REAL;
