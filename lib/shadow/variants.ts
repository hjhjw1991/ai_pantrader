/**
 * 影子盘的第一批变体。
 *
 * 选这几套，是因为它们各自回答一个具体的问题，而不是"多跑几套总有一套好"：
 *
 *   baseline         对照组。v2 的 baseline 槽组合，与 v1 逐字段一致（parity 保证）
 *   结构位定价        只换评估器：按盈亏比取舍、排序，值不值？
 *   五段状态机        只换择时器：按情绪阶段定档位，比"今天盘面强不强"好不好？
 *   五段+结构位       两个一起换：效果是叠加还是互相抵消？
 *   五段高潮进攻+结构位 样本内检验里高潮日次日溢价显著偏高（t = 2.1），
 *                    与"高潮不追"的默认映射相反 —— 让真实候选来裁决
 *   只做启动发酵+结构位 冷启动回放里冰点开仓最差、启动最好，于是只在启动 / 发酵开仓。
 *                    同样是样本内挑出来的，毕业只认实盘
 *   申万主线（三套）   主线不靠写死的必查链，由申万行业的涨停分布决定。单换主线识别器一套，
 *                    另两套叠在目前回放最好的两个组合上
 *
 * 一次只换一个槽的变体是刻意的：两个槽一起换，赢了也分不清是谁的功劳。
 * id 一经写进台账就不能改（样本按它归因）；要改组合就新开一个 id。
 *
 * **游资变体（四套）是例外，且必须知道代价**：它们一次换三到四个槽。
 *
 * 这不是偷懒 —— 游资打法的"选股 / 进场 / 离场"是一整套互相咬合的动作，
 * 把"二板打板"的候选配上"−3% 低吸"的触发价，产出的既不是打板也不是低吸，
 * 而是谁都没做过的第三种东西，赢了也无从归因。所以按**人**整套搬，不按槽拆。
 *
 * 代价是 Bonferroni：候选从 9 套涨到 13 套，多重比较校正后的 t 门槛随之抬高，
 * 每一套的毕业都变难了。这是有意的取舍 —— 宁可少而能说清，不要多而分不清。
 * 四套而不是十套，就是冲着这个代价定的。
 *
 * 另一个必须记住的前提：这几套打法在**真实执行**上都要求盯盘（打板尤其如此），
 * 而系统的使用者不盯盘。影子盘记的是"若按此价成交后来会怎样"，
 * 跑赢只说明选股与离场有 alpha，不说明执行得了 —— 毕业最终由人批准（前 2 次手动）。
 */
